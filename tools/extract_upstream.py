#!/usr/bin/env python3
"""Reproduce or verify the three unchanged Suricata packet match functions.

Only Python's standard library is required.  Original source files are kept in
upstream/suricata, with their hashes in upstream/manifest.json.  The optional
--source-dir points at another unpacked copy of the supplied Suricata tree.
"""
# SPDX-License-Identifier: GPL-2.0-only

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parent.parent
FUNCTIONS = (
    ("src/detect-dsize.c", "DetectDsizeMatch"),
    ("src/detect-itype.c", "DetectITypeMatch"),
    ("src/detect-icode.c", "DetectICodeMatch"),
)


def mask_c_literals(text: str) -> str:
    """Mask comments and strings while preserving offsets and newlines.

    Braces inside quoted strings, character literals, or comments must not be
    counted as function boundaries. Escaped quotes and line continuations are
    consumed with their literal instead of ending it prematurely.
    """
    chars = list(text)
    i = 0
    while i < len(text):
        begin = i
        if text.startswith("//", i):
            end = text.find("\n", i + 2)
            i = len(text) if end < 0 else end
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2)
            if end < 0:
                raise ValueError("unterminated C block comment")
            i = end + 2
        elif text[i] in ('"', "'"):
            quote = text[i]
            i += 1
            while i < len(text):
                if text[i] == "\\":
                    i += 2
                elif text[i] == quote:
                    i += 1
                    break
                else:
                    i += 1
            else:
                raise ValueError("unterminated C string or character literal")
        else:
            i += 1
            continue
        for j in range(begin, min(i, len(chars))):
            if chars[j] not in "\r\n":
                chars[j] = " "
    return "".join(chars)


def extract_function(text: str, name: str) -> tuple[str, int, int]:
    masked = mask_c_literals(text)
    pattern = re.compile(r"\bstatic\s+int\s+" + re.escape(name) + r"\s*\(")
    definitions = []
    for match in pattern.finditer(masked):
        i = match.end()
        depth = 1
        while i < len(masked) and depth:
            depth += (masked[i] == "(") - (masked[i] == ")")
            i += 1
        while i < len(masked) and masked[i].isspace():
            i += 1
        if i == len(masked) or masked[i] != "{":
            continue  # A forward declaration, rather than the definition.
        depth = 1
        i += 1
        while i < len(masked) and depth:
            depth += (masked[i] == "{") - (masked[i] == "}")
            i += 1
        if depth:
            raise ValueError(f"unbalanced braces in {name}")
        start = match.start()
        definitions.append((text[start:i], text.count("\n", 0, start) + 1,
                            text.count("\n", 0, i) + 1))
    if len(definitions) != 1:
        raise ValueError(f"expected one definition of {name}, found {len(definitions)}")
    return definitions[0]


def source_license(text: str) -> str:
    if not text.startswith("/* Copyright"):
        raise ValueError("expected upstream copyright and GPL header")
    end = text.find("*/")
    if end < 0:
        raise ValueError("unterminated upstream license header")
    return text[:end + 2]


def generate(source_dir: Path) -> tuple[bytes, list[dict]]:
    pieces = [
        "/* Generated by tools/extract_upstream.py; do not edit manually.\n"
        " * The three function definitions below are byte-for-byte extractions\n"
        " * from the supplied Suricata source. Compatibility shims live in\n"
        " * predicates.c. See upstream/PROVENANCE.md.\n */\n"
    ]
    metadata = []
    for relative, name in FUNCTIONS:
        raw = (source_dir / relative).read_bytes()
        text = raw.decode("utf-8")
        body, first, last = extract_function(text, name)
        pieces.append(f"\n/* Source: {relative}; function: {name}. */\n")
        pieces.append(source_license(text) + "\n\n")
        pieces.append(body + "\n")
        metadata.append({
            "source": relative,
            "function": name,
            "first_line": first,
            "last_line": last,
            "function_sha256": hashlib.sha256(body.encode("utf-8")).hexdigest(),
        })
    return "".join(pieces).encode("utf-8"), metadata


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verify", action="store_true",
                        help="verify source hashes and generated output without writing")
    parser.add_argument("--source-dir", type=Path,
                        default=ROOT / "upstream" / "suricata")
    args = parser.parse_args()
    try:
        manifest = json.loads((ROOT / "upstream" / "manifest.json").read_text("utf-8"))
        for relative, expected in manifest["original_files_sha256"].items():
            actual = hashlib.sha256((args.source_dir / relative).read_bytes()).hexdigest()
            if actual != expected:
                raise ValueError(f"original source hash mismatch: {relative}")
        generated, functions = generate(args.source_dir)
        if functions != manifest["extracted_functions"]:
            raise ValueError("extracted functions differ from the recorded originals")
        destination = ROOT / "src" / "suricata_matchers.inc"
        if args.verify:
            if destination.read_bytes() != generated:
                raise ValueError("src/suricata_matchers.inc does not match the original functions")
            print("Verified: 10 original files, 3 unchanged extracted functions.")
        else:
            destination.write_bytes(generated)
            print("Generated src/suricata_matchers.inc from verified original files.")
        return 0
    except (OSError, UnicodeError, ValueError, KeyError) as exc:
        print(f"Extraction error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
